export const locale = language => language === 'en' ? 'en-US' : 'vi-VN';
export function tr(language, text, values = {}) {
  const singular = {
    '{count} lần vận động':'{count} movement break',
    '{count} điều tốt':'{count} act of care',
    '{count} lần uống · Từng ngụm nhỏ đều đáng quý.':'{count} drink · Every sip counts.',
    'Thêm {count} lần uống nước hoặc vận động để lớn thêm.':'{count} more drink or movement break to reach the next stage.'
  };
  const template = language === 'en' ? (values.count === 1 && singular[text] ? singular[text] : (english[text] ?? text)) : text;
  return template.replace(/\{(\w+)\}/g, (match,key) => values[key] ?? match);
}
export function translateError(language, text) {
  const range = /^Giá trị cần từ (\d+) đến (\d+)\.$/.exec(text);
  return range ? tr(language,'Giá trị cần từ {min} đến {max}.',{min:range[1],max:range[2]}) : tr(language,text);
}
const originals = new WeakMap();
export function translateDocument(document, language) {
  document.documentElement.lang = language;
  document.title = tr(language,'Mầm • Chăm mình một chút');
  const walker = document.createTreeWalker(document.body,4);
  while(walker.nextNode()) {
    const node=walker.currentNode;
    if (['SCRIPT','STYLE'].includes(node.parentElement?.tagName)) continue;
    if (!originals.has(node)) originals.set(node,node.nodeValue);
    const original=originals.get(node),trimmed=original.trim();
    if (trimmed in english) node.nodeValue=original.replace(trimmed,tr(language,trimmed));
  }
  for(const element of document.querySelectorAll('[aria-label]')) {
    if(!originals.has(element)) originals.set(element,element.getAttribute('aria-label'));
    element.setAttribute('aria-label',tr(language,originals.get(element)));
  }
}
